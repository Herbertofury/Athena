import assert from 'node:assert/strict';
import {mkdtemp,readFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {chromium} from 'playwright';
import {buildReplay} from '../build-replay.mjs';
const dir=await mkdtemp(resolve(tmpdir(),'warden-browser-fixture-'));
const browser=await chromium.launch();
try{
 await buildReplay(resolve(dir,'node-adapter'));
 const {decodeTape,encodeTape,newMatch}=await import(pathToFileURL(resolve(dir,'node-adapter/portable-tape.mjs')));
 const address=pathToFileURL(resolve('Athena-Warden-Duel.html')).href;
 const page=await browser.newPage({offline:true,acceptDownloads:true,viewport:{width:1170,height:920}});
 const findings=[],ext=[];
 page.on('pageerror',e=>findings.push(e.message));
 page.on('console',m=>{if(m.type()==='error')findings.push(m.text());});
 page.on('request',req=>ext.push(req.url()));
 await page.goto(address);
 const status=page.locator('#status');
 assert.match(await status.textContent(),/Select your starting cards/);
 await page.locator('#keep-cards button').first().press('Enter');
 await page.locator('#keep-cards button').nth(2).press('Enter');
 assert.equal(await page.locator('#keep-cards button[aria-pressed=true]').count(),2);
 await page.getByRole('button',{name:'Begin with selected cards'}).press('Enter');
 assert.equal(await page.locator('#turn').textContent(),'1');
 const play=page.locator('#hand button:not([disabled])').first();
 await play.click();assert.equal(await page.locator('#field button').count(),1);
 const ready=page.locator('#field button:not([disabled])').first();
 await ready.click();const hp=await page.locator('#their-hp').textContent();
 await page.getByRole('button',{name:'Attack opposing hero'}).click();
 assert.notEqual(await page.locator('#their-hp').textContent(),hp);
 await page.getByRole('button',{name:'End turn'}).click();
 assert.equal(await page.locator('#turn').textContent(),'2');
 await page.getByText('New match or portable replay',{exact:true}).click();
 const downloaded=page.waitForEvent('download');
 await page.getByRole('button',{name:'Download replay tape'}).click();
 const exportPath=resolve(dir,'browser.json');await (await downloaded).saveAs(exportPath);
 const original=decodeTape(await readFile(exportPath,'utf8'));
 assert.equal(original.view().state.turn,2);
 assert.ok(original.view().state.enemyHp<24);
 const fresh=newMatch(42);
 fresh.apply({type:'mulligan',kept:[0]});fresh.apply({type:'end'});fresh.apply({type:'end'});
 const raw=encodeTape(fresh);
 const selected=page.getByLabel('Replay file');
 await selected.setInputFiles({name:'modified.json',mimeType:'application/json',buffer:Buffer.from(raw.replace('"seed":42','"seed":99'))});
 await page.getByRole('button',{name:'Verify and resume'}).click();
 await page.locator('#tape-status').filter({hasText:'Not loaded.'}).waitFor();
 assert.equal(await page.locator('#turn').textContent(),'2');
 await selected.setInputFiles({name:'node.json',mimeType:'application/json',buffer:Buffer.from(raw)});
 await page.getByRole('button',{name:'Verify and resume'}).click();
 await page.locator('#tape-status').filter({hasText:'Verified and loaded the tape.'}).waitFor();
 assert.equal(await page.locator('#turn').textContent(),'3');
 await page.getByRole('button',{name:'End turn'}).click();
 assert.equal(await page.locator('#turn').textContent(),'4');
 assert.deepEqual(findings,[]);
 assert.deepEqual(ext,[address]);
 console.log('Actual offline keyboard/mouse combat, Node ↔ browser replay interchange, tamper refusal, no external requests.');
}finally{await browser.close();await rm(dir,{recursive:true,force:true});}
